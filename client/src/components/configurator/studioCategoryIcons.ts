export function studioCategoryIcon(id: string, title = ""): LucideIcon {
  // A source may be a creative reference or an analytics account.
  if (/account.*dates|account.*range/i.test(title)) return CalendarDays;
  if (/report output|latest run/i.test(title)) return BarChart3;
  const key = id.split("/").pop()!.toLowerCase().replaceAll(" ", "_");
  if (key === "choice" && icons[title.toLowerCase().replaceAll(" ", "_")])
    return icons[title.toLowerCase().replaceAll(" ", "_")];
  return (
    icons[key] ?? icons[title.toLowerCase().replaceAll(" ", "_")] ?? LayoutGrid
  );
}
